/**
 * 生成一个整圆的子路径片段。和外层形状的 `d` 拼在一起、并给 `<path>` 加上
 * `fillRule="evenodd"`，就能在实心图形里抠出一个圆形镂空 —— 这是在纯 fill
 * （不描边、不叠同色半透明层，因为同色叠加不产生任何可见差异）的前提下，
 * 画瓢虫黑点、天牛星点这类「洞」最可靠的办法。
 */
const circleHole = (cx: number, cy: number, r: number) =>
  `M${cx + r},${cy} A${r},${r} 0 1 0 ${cx - r},${cy} A${r},${r} 0 1 0 ${cx + r},${cy} Z`

/**
 * 镜像容器：只画左半边，通过 `translate(24,0) scale(-1,1)`
 * 沿 x=12 中轴生成右半边，保证左右严格对称（避免手抄坐标产生误差）。
 */
const Pair = ({ children }: { children: ReactNode }) => (
  <>
    {children}
    <g transform="translate(24,0) scale(-1,1)">{children}</g>
  </>
)

/**
 * 一节肢体（腿的一整条，或触角的一节）：从锚点 (x, y) 沿 angle 方向伸出的圆头细条。
 * angle 的 0° 为竖直向下，顺时针增大（90°=指向左侧，180°=指向正上方）。
 * 这样"前足更靠上前方、后足更靠下后方"只需调整 angle 即可，不必手算端点坐标。
 */
const Limb = ({
  x,
  y,
  angle,
  length,
  width = 1,
  club = false,
}: {
  x: number
  y: number
  angle: number
  length: number
  width?: number
  club?: boolean
}) => (
  <g transform={`translate(${x} ${y}) rotate(${angle})`}>
    <rect x={-width / 2} y={0} width={width} height={length} rx={width / 2} />
    {club ? <circle cx={0} cy={length} r={width * 0.6} /> : null}
  </g>
)

/**
 * 两节带"膝"弯折的肢体：螳螂举起的镰刀前足、蝗虫折叠的粗大后腿、
 * 蚂蚁/蜜蜂膝状弯曲的触角都用它。angle1 相对锚点，angle2 相对上一节末端。
 */
const BentLimb = ({
  x,
  y,
  angle1,
  len1,
  angle2,
  len2,
  width = 1,
}: {
  x: number
  y: number
  angle1: number
  len1: number
  angle2: number
  len2: number
  width?: number
}) => (
  <g transform={`translate(${x} ${y}) rotate(${angle1})`}>
    <rect x={-width / 2} y={0} width={width} height={len1} rx={width / 2} />
    <g transform={`translate(0 ${len1}) rotate(${angle2})`}>
      <rect x={(-width * 0.75) / 2} y={0} width={width * 0.75} height={len2} rx={(width * 0.75) / 2} />
    </g>
  </g>
)

