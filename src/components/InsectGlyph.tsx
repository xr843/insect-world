/**
 * 昆虫剪影图标集 —— 32 种昆虫的俯视（背面）剪影，统一 24x24 视窗。
 * 全部手写路径坐标，不引外部依赖，实心填充为主，不用描边。
 *
 * 视角约定：头在上（y 小），尾在下（y 大），左右沿 x=12 中轴对称。
 */
import type { ReactNode } from 'react'

export type InsectGlyphProps = { id: string; size?: number; color?: string }

